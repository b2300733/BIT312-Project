CREATE DATABASE IF NOT EXISTS serviceday_db;
USE serviceday_db;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL,
  department VARCHAR(255) NOT NULL,
  role ENUM('employee', 'admin') DEFAULT 'employee',
  createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS activities (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  serviceType VARCHAR(255) NOT NULL,
  scheduleDate VARCHAR(50) NOT NULL,
  scheduleTime VARCHAR(50) NOT NULL,
  location VARCHAR(255) NOT NULL,
  registered INT DEFAULT 0,
  totalSlots INT NOT NULL,
  cutoffDate VARCHAR(50) NOT NULL,
  cutoffTime VARCHAR(50) NOT NULL,
  description TEXT NOT NULL,
  createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS registrations (
  id INT AUTO_INCREMENT PRIMARY KEY,
  employeeId INT NOT NULL,
  activityId INT NOT NULL,
  qrData VARCHAR(255) UNIQUE DEFAULT NULL,
  qrGeneratedAt DATETIME DEFAULT NULL,
  qrchecked BOOLEAN DEFAULT FALSE,
  checkedInAt DATETIME DEFAULT NULL,
  createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY unique_employee_activity (employeeId, activityId),
  CONSTRAINT fk_reg_user FOREIGN KEY (employeeId) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_reg_activity FOREIGN KEY (activityId) REFERENCES activities(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS reminders (
  id INT AUTO_INCREMENT PRIMARY KEY,
  activity VARCHAR(255) NOT NULL,
  type VARCHAR(255) NOT NULL,
  scheduledFor VARCHAR(255) NOT NULL,
  status ENUM('sent', 'pending') DEFAULT 'pending',
  createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);